#!/usr/bin/env python3
"""
Dvargosh Module Scaffolding & Templating Tool
Creates new Dvargosh modules from templates with non-monolithic services,
attribution markers, memory spaces, and unit tests.
Supports both rich interactive wizard and fully automated CI/CD CLI flags.
"""

import os
import sys
import argparse
from pathlib import Path

# Add pipeline directory to sys.path
SCRIPT_DIR = Path(__file__).resolve().parent
ROOT_DIR = SCRIPT_DIR.parent
sys.path.insert(0, str(SCRIPT_DIR))

import ui

def generate_module(
    name: str,
    domain: str,
    mod_type: str,
    description: str,
    author: str,
    secured_kb: int,
    target_dir: Path
):
    mod_dir = target_dir / name
    test_dir = mod_dir / "test"
    mod_dir.mkdir(parents=True, exist_ok=True)
    test_dir.mkdir(parents=True, exist_ok=True)

    class_name = "".join(part.capitalize() for part in name.split("_")) + "Module"
    primary_domain = f"{name}:{domain}" if ":" not in domain else domain

    # 1. Module Class & Manifest: <name>_module.cpp
    module_cpp = f"""// Auto-generated by Dvargosh Module Scaffolder.
#include "dvargosh/dvargosh.hpp"

namespace dvargosh {{

/**
 * @brief Main module lifecycle and manifest controller for '{name}'.
 */
class {class_name} : public IModule {{
public:
    const ModuleManifest& manifest() const override {{
        static ModuleManifest s_manifest = []() {{
            ModuleManifest m;
            m.name = "{name}";
            m.domain = "*"; // Scoped to {name}.*
            m.version = Version{{1, 0, 0}};
            m.description = "{description}";
            m.author = "{author}";
            m.requested_permissions = PermissionSet::all();
            return m;
        }}();
        return s_manifest;
    }}

    Result<void> on_load(ModuleContext& ctx) override {{
        // Automatically registers functions declared across non-monolithic source files
        register_auto_functions(ctx);
        return Result<void>::success();
    }}

    Result<void> on_start(ModuleContext&) override {{
        return Result<void>::success();
    }}

    Result<void> on_stop(ModuleContext&) override {{
        return Result<void>::success();
    }}

    Result<void> on_unload(ModuleContext&) override {{
        return Result<void>::success();
    }}
}};

}} // namespace dvargosh

DVARGOSH_EXPORT_MODULE(dvargosh::{class_name})
"""
    with open(mod_dir / f"{name}_module.cpp", "w") as f:
        f.write(module_cpp)

    # 2. Services File: <name>.services.cpp
    if mod_type == "crypto" or mod_type == "vault":
        services_cpp = f"""// Auto-generated by Dvargosh Module Scaffolder.
#include "dvargosh/dvargosh.hpp"
#include <string>

namespace dvargosh {{

/**
 * @brief Cryptographic/Vault service method for '{name}'.
 * Decorated with attribution marker for pipeline code generation.
 */
DVARGOSH_SERVICE({primary_domain})
std::string {name}_secure_hash(const std::string& input) {{
    return "SECURE_" + Crypto::sha256_hex(input);
}}

DVARGOSH_SERVICE({primary_domain})
std::string {name}_verify_status(const std::string& id) {{
    return "VERIFIED_ID_" + id;
}}

}} // namespace dvargosh
"""
    elif mod_type == "compute":
        services_cpp = f"""// Auto-generated by Dvargosh Module Scaffolder.
#include "dvargosh/dvargosh.hpp"
#include <cmath>
#include <string>

namespace dvargosh {{

/**
 * @brief Computational service method for '{name}'.
 */
DVARGOSH_SERVICE({primary_domain})
double {name}_compute_hypot(double a, double b) {{
    return std::hypot(a, b);
}}

DVARGOSH_SERVICE({primary_domain})
std::string {name}_status(const std::string& worker_id) {{
    return "WORKER_READY_" + worker_id;
}}

}} // namespace dvargosh
"""
    else:
        services_cpp = f"""// Auto-generated by Dvargosh Module Scaffolder.
#include "dvargosh/dvargosh.hpp"
#include <string>

namespace dvargosh {{

/**
 * @brief Standard service method for '{name}'.
 * Clean native C++ function; pipeline auto-generates RPC bridge and typed proxy.
 */
DVARGOSH_SERVICE({primary_domain})
std::string {name}_echo(const std::string& input) {{
    return "[{name}] " + input;
}}

}} // namespace dvargosh
"""
    with open(mod_dir / f"{name}.services.cpp", "w") as f:
        f.write(services_cpp)

    # 3. Dedicated Module Unit Test: test/test_<name>.cpp
    test_cpp = f"""// Auto-generated unit test for '{name}'.
#include "dvargosh/dvargosh.hpp"
#include <cassert>
#include <iostream>

using namespace dvargosh;

int main() {{
    std::cout << "[Test: {name}] Initializing verification harness...\\n";
    auto di = std::make_shared<DIContainer>();
    ModuleLoader loader(di);

    loader.add_search_path("./build/modules");
    loader.add_search_path("./build/development_modules");

    auto file_res = loader.find_module_file("{name}");
    if (file_res.is_ok()) {{
        auto load_res = loader.load_from_file(file_res.value());
        assert(load_res.is_ok());
        std::cout << "  ✓ Module '{name}' successfully loaded and verified.\\n";
    }} else {{
        std::cout << "  ℹ Module binary not yet built; skipping runtime dynamic test.\\n";
    }}
    return 0;
}}
"""
    with open(test_dir / f"test_{name}.cpp", "w") as f:
        f.write(test_cpp)

    # 4. Initial module.def
    def_content = f"""[module]
name = {name}
version = 1.0.0
description = {description}
author = {author}
secured_memory_kb = {secured_kb}
domains = {primary_domain}, *
sources = {name}_module.cpp, {name}.services.cpp
link_libraries = dvargosh_core
auto_load = true
"""
    with open(mod_dir / "module.def", "w") as f:
        f.write(def_content)

    # 5. README.md
    readme_content = f"""# Module: `{name}`

{description}

* **Author**: {author}
* **Subsystem Domain**: `{primary_domain}`
* **Secured Memory Allocation**: {secured_kb} KB
* **Scoped Wildcard**: `{name}.*`

## Building and Verification
```bash
make full-pipeline
```
"""
    with open(mod_dir / "README.md", "w") as f:
        f.write(readme_content)

    ui.print_success(f"Scaffolded module in: {mod_dir.relative_to(ROOT_DIR)}")
    return mod_dir

def parse_args():
    parser = argparse.ArgumentParser(
        description="Dvargosh Module Scaffolder CLI (supports interactive & CI/CD modes)"
    )
    parser.add_argument("--name", help="Unique name of the module (e.g. telemetry, crypto_vault)")
    parser.add_argument("--domain", default="core", help="Primary subsystem domain (e.g. core, worker, vault)")
    parser.add_argument(
        "--type",
        choices=["service", "crypto", "compute", "vault"],
        default="service",
        help="Module architectural archetype"
    )
    parser.add_argument("--description", default="Dvargosh Subsystem Module", help="Module description")
    parser.add_argument("--author", default="Dvargosh Developer", help="Module author name")
    parser.add_argument("--secured-memory-kb", type=int, default=2048, help="Hardware-guarded memory quota in KB")
    parser.add_argument(
        "--target-dir",
        choices=["development_modules", "modules"],
        default="development_modules",
        help="Target parent directory"
    )
    parser.add_argument("--non-interactive", action="store_true", help="Run without interactive prompts (for CI/CD)")
    return parser.parse_args()

def main():
    args = parse_args()

    # Determine if running interactively
    is_interactive = not args.non_interactive and not args.name

    if is_interactive:
        ui.print_banner("DVARGOSH MODULE SCAFFOLDER", "Interactive Architecture & Template Wizard")
        name = ui.prompt_text("Module Name (lowercase, e.g. neural_net, telecom)", default="sample_service")
        domain = ui.prompt_text("Primary Subsystem Domain", default="core")
        mod_type = ui.prompt_choice(
            "Select Module Archetype",
            choices=["service", "crypto", "compute", "vault"],
            default="service"
        )
        description = ui.prompt_text("Description", default=f"High-performance {mod_type} module for Dvargosh")
        author = ui.prompt_text("Author", default="Dvargosh Developer")
        target_dir_name = ui.prompt_choice(
            "Target Directory",
            choices=["development_modules", "modules"],
            default="development_modules"
        )
        secured_kb = 2048
    else:
        if not args.name:
            ui.print_error("Module name is required in non-interactive mode. Use --name <name>")
            sys.exit(1)
        name = args.name.lower().strip()
        domain = args.domain.lower().strip()
        mod_type = args.type
        description = args.description
        author = args.author
        target_dir_name = args.target_dir
        secured_kb = args.secured_memory_kb

    target_dir = ROOT_DIR / target_dir_name
    mod_dir = generate_module(
        name=name,
        domain=domain,
        mod_type=mod_type,
        description=description,
        author=author,
        secured_kb=secured_kb,
        target_dir=target_dir
    )

    # Automatically trigger pipeline generator to register newly scaffolded module
    ui.print_info("Updating pipeline generator & auto-generating typed proxy headers...")
    os.system(f"python3 {SCRIPT_DIR}/generator.py > /dev/null")
    ui.print_success("Module registered into pipeline and CMake targets.")

if __name__ == "__main__":
    main()
