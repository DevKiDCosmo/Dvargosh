#!/usr/bin/env python3
"""
Dvargosh Module Tool:
- Reads module.def manifests
- Auto-generates missing CMake configuration and target linkings (modules/Modules.cmake)
- Cryptographically signs module dynamic libraries with HMAC-SHA256
- Validates module structure and integrity
"""

import os
import sys
import re
import configparser
import hmac
import hashlib
import json
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
MODULES_DIR = ROOT_DIR / "modules"
CMAKE_MODULES_FILE = MODULES_DIR / "Modules.cmake"

def parse_module_def(def_path):
    config = configparser.ConfigParser()
    try:
        config.read(def_path)
    except Exception as e:
        raise ValueError(f"Malformed manifest {def_path}: {e}")

    if "module" not in config:
        raise ValueError(f"Missing [module] section in {def_path}")
    sec = config["module"]
    name = sec.get("name")
    if not name or not re.match(r'^[a-zA-Z0-9_]+$', name):
        raise ValueError(f"Invalid module name '{name}' in {def_path}: must match ^[a-zA-Z0-9_]+$")

    raw_sources = [s.strip() for s in sec.get("sources", "").split(",") if s.strip()]
    for src in raw_sources:
        p = Path(src)
        if p.is_absolute() or ".." in p.parts:
            raise ValueError(f"Path traversal or absolute path detected in sources of module '{name}' ({def_path}): {src}")

    raw_links = [l.strip() for l in sec.get("link_libraries", "dvargosh_core").split(",") if l.strip()]
    for lib in raw_links:
        if not re.match(r'^[a-zA-Z0-9_]+$', lib):
            raise ValueError(f"Invalid link library target '{lib}' in {def_path}")

    return {
        "name": name,
        "version": sec.get("version", "1.0.0"),
        "description": sec.get("description", ""),
        "author": sec.get("author", "Dvargosh"),
        "secured_memory_kb": sec.getint("secured_memory_kb", 2048),
        "domains": [d.strip() for d in sec.get("domains", "default").split(",")],
        "sources": raw_sources,
        "link_libraries": raw_links,
        "dir": def_path.parent
    }

def discover_modules():
    modules = []
    for root, _, files in os.walk(MODULES_DIR):
        if "module.def" in files:
            def_path = Path(root) / "module.def"
            try:
                mod_info = parse_module_def(def_path)
                modules.append(mod_info)
            except Exception as e:
                print(f"[ERROR] Failed parsing manifest {def_path}: {e}", file=sys.stderr)
                sys.exit(1)
    return modules

def generate_cmake(modules):
    print(f"Generating CMake configuration for {len(modules)} modules -> {CMAKE_MODULES_FILE}")
    lines = [
        "# Auto-generated by tools/dvargosh_tool.py - DO NOT EDIT MANUALLY",
        "# Scans module.def manifests and builds dynamic library targets\n",
        "set(DVARGOSH_ALL_MODULE_TARGETS \"\")\n"
    ]

    for m in modules:
        rel_dir = m["dir"].relative_to(ROOT_DIR)
        target_name = f"mod_{m['name']}"
        source_paths = [f"{rel_dir}/{src}" for src in m["sources"]]
        sources_str = " ".join(source_paths)
        links_str = " ".join(m["link_libraries"])

        lines.append(f"# Module: {m['name']} (Domains: {', '.join(m['domains'])})")
        lines.append(f"add_library({target_name} SHARED {sources_str})")
        lines.append(f"target_link_libraries({target_name} PRIVATE {links_str})")
        lines.append(f"target_include_directories({target_name} PRIVATE include {rel_dir})")
        lines.append(f"set_target_properties({target_name} PROPERTIES")
        lines.append(f"    PREFIX \"lib\"")
        lines.append(f"    LIBRARY_OUTPUT_DIRECTORY ${{CMAKE_BINARY_DIR}}/modules")
        lines.append(")")
        lines.append(f"list(APPEND DVARGOSH_ALL_MODULE_TARGETS {target_name})\n")

    with open(CMAKE_MODULES_FILE, "w") as f:
        f.write("\n".join(lines))
    print(f"[SUCCESS] Wrote {CMAKE_MODULES_FILE}")

def sign_modules(build_dir, secret_key):
    modules_dir = Path(build_dir) / "modules"
    if not modules_dir.exists():
        modules_dir = Path(build_dir)
    if not modules_dir.exists():
        print(f"[ERROR] Modules directory not found at {modules_dir}")
        sys.exit(1)

    signatures = {}
    print(f"Signing modules in {modules_dir} with secret key...")
    exts = [".dylib", ".so"]
    for file in modules_dir.iterdir():
        if file.suffix in exts and file.name.startswith("libmod_"):
            with open(file, "rb") as f:
                data = f.read()
            digest = hashlib.sha256(data).hexdigest()
            sig = hmac.new(secret_key.encode("utf-8"), digest.encode("utf-8"), hashlib.sha256).hexdigest()
            signatures[file.name] = {
                "sha256": digest,
                "hmac_sha256": sig,
                "size_bytes": len(data)
            }
            print(f"  * {file.name} -> {sig}")

    sig_file = modules_dir / "signatures.json"
    with open(sig_file, "w") as f:
        json.dump(signatures, f, indent=2)
    print(f"[SUCCESS] Signatures recorded in {sig_file}")

def main():
    if len(sys.argv) < 2:
        print("Usage: dvargosh_tool.py <command> [args...]")
        print("Commands:")
        print("  generate-cmake          Auto-generate modules/Modules.cmake from module.def manifests")
        print("  list                    List all discovered modules and domains")
        print("  sign <build_dir> <key>  Sign all dynamic library modules")
        return

    cmd = sys.argv[1]
    if cmd == "generate-cmake":
        mods = discover_modules()
        generate_cmake(mods)
    elif cmd == "list":
        mods = discover_modules()
        print(f"Discovered {len(mods)} modules:")
        for m in mods:
            print(f"  * {m['name']} v{m['version']} | Domains: {m['domains']} | Dir: {m['dir'].name}")
    elif cmd == "sign":
        if len(sys.argv) < 4:
            print("Usage: dvargosh_tool.py sign <build_dir> <secret_key>")
            sys.exit(1)
        sign_modules(sys.argv[2], sys.argv[3])
    else:
        print(f"Unknown command: {cmd}")

if __name__ == "__main__":
    main()
